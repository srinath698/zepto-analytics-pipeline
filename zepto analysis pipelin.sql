--finding outofstock products
SELECT OUTOFSTOCK,COUNT(SKU_ID)
FROM ZEPTO_ANALYSIS 
GROUP BY OUTOFSTOCK;
--stockkeeping units in dataset
SELECT NAME,COUNT(SKU_ID) AS "STOCK KEEPING UNITS"
FROM ZEPTO_ANALYSIS
GROUP BY NAME
HAVING COUNT(SKU_ID)>1
ORDER BY COUNT(SKU_ID) DESC;
--finding free or 0 products 
SELECT * FROM ZEPTO_ANALYSIS 
WHERE MRP=0 OR DISCOUNTEDSELLINGPRICE=0;
DELETE FROM ZEPTO_ANALYSIS
WHERE MRP=0;
--removing free or 0 products
UPDATE ZEPTO_ANALYSIS 
