DISCOUNTEDSELLINGPRICE=DISCOUNTEDSELLINGPRICE/100.0;
SELECT MRP,DISCOUNTEDSELLINGPRICE FROM ZEPTO_ANALYSIS


--1.WHICH PRODUCT HAS THE HIGHEST DISCOUNT
SELECT DISTINCT NAME,MRP,DISCOUNTEDSELLINGPRICE,DISCOUNTPERCENTAGE
FROM ZEPTO_ANALYSIS
ORDER BY DISCOUNTEDSELLINGPRICE DESC
LIMIT 20;

--2.WHAT ARE THE PRODUCT WITH HIGH MRP 
SELECT DISTINCT NAME,MRP
FROM ZEPTO_ANALYSIS
ORDER BY MRP DESC
LIMIT 10;

--3.WT ARE THE PRODUCT WITH HIGH MRP BUT OUTOFSTOCK
SELECT DISTINCT NAME,MRP
FROM ZEPTO_ANALYSIS
WHERE OUTOFSTOCK=TRUE AND MRP>300
ORDER BY MRP DESC;

--4.CALCULATE THE ESTIMATES REVENUE BY CATEGORY
SELECT CATEGORY,
SUM(discountedSellingPrice *AVALIABLE_QUANTITY) AS TOTAL_REVENUE
FROM ZEPTO_ANALYSIS
GROUP BY CATEGORY 
ORDER BY TOTAL_REVENUE  DESC;

--5.FIND ALL PRODUCTS WHERE MRP IS GREATER THAN 500 AND DISCOUNT IS LESS THAN 10%
SELECT DISTINCT NAME ,MRP,DISCOUNTPERCENTAGE

FROM ZEPTO_ANALYSIS
WHERE MRP>500 AND DISCOUNTPERCENTAGE <10
ORDER BY MRP DESC,DISCOUNTPERCENTAGE DESC;

--6.IDENTIFY THE TOP 5 CATEGORIES OFFERING THE HIGHEST AVG DISCOUNT PERCENTAGE
SELECT CATEGORY,
ROUND(AVG(DISCOUNTPERCENTAGE),2) AS AVG_DISCOUNT
FROM ZEPTO_ANALYSIS
GROUP BY CATEGORY
ORDER BY AVG_DISCOUNT DESC
LIMIT 5;
--7.group the products by category like low,medium,bulk
select  distinct name,weightin_gms,
case 
     when weightin_gms<1000 then 'low'
     when weightin_gms<5000 then 'medium'
	 else 'bulk'
end as weight_category
from zepto_analysis;
--8.wts the total inventory weight per category 
select category,
sum(weightin_gms*AVALIABLE_QUANTITY)AS TOTAL_WEIGHT
from zepto_analysis
group by category
order by total_weight DESC;





